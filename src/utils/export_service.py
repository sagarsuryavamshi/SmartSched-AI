"""Timetable Export Services for CSV and PDF.

Provides high-fidelity, institution-ready tabular CSV exports and
professional styled PDF documents for faculty, classrooms, and student cohorts.
"""

import io
from typing import Any, Dict, List, Optional
import pandas as pd

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter, landscape
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

from src.utils.logger import setup_logger

logger = setup_logger("smartsched.utils.export")


def export_timetable_to_csv(schedule_records: List[Dict[str, Any]]) -> str:
    """Converts timetable schedule records to a standardized CSV format."""
    if not schedule_records:
        return "Assignment ID,Course Code,Course Title,Day,Start Time,End Time,Classroom,Instructor,Cohort\n"

    rows = []
    for r in schedule_records:
        rows.append({
            "Assignment ID": r.get("assignment_id", ""),
            "Course Code": r.get("course_code", ""),
            "Course Title": r.get("course_title", ""),
            "Category": r.get("course_category", "Theory"),
            "Day": r.get("day", ""),
            "Start Time": r.get("start_time", ""),
            "End Time": r.get("end_time", ""),
            "Classroom": r.get("room_id", ""),
            "Room Type": r.get("room_type", ""),
            "Instructor": r.get("faculty_name", r.get("faculty_id", "")),
            "Cohort": r.get("group_name", r.get("group_id", "")),
        })

    df = pd.DataFrame(rows)
    day_order = {"Monday": 1, "Tuesday": 2, "Wednesday": 3, "Thursday": 4, "Friday": 5, "Saturday": 6}
    df["day_num"] = df["Day"].map(day_order)
    df.sort_values(by=["day_num", "Start Time", "Classroom"], inplace=True)
    df.drop(columns=["day_num"], inplace=True)

    return df.to_csv(index=False)


def export_timetable_to_pdf(
    schedule_records: List[Dict[str, Any]],
    title: str = "SmartSched AI University Timetable",
    filter_label: Optional[str] = None,
) -> bytes:
    """Generates an institutional landscape PDF document of the timetable."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=landscape(letter),
        rightMargin=0.5 * inch,
        leftMargin=0.5 * inch,
        topMargin=0.5 * inch,
        bottomMargin=0.5 * inch,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#0D47A1"),
        alignment=0,
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#546E7A"),
        alignment=0,
    )
    cell_style = ParagraphStyle(
        "TableCell",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8,
        leading=10,
        alignment=0,
    )
    header_style = ParagraphStyle(
        "TableHeader",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.white,
        alignment=0,
    )

    elements = []

    # Title & Subtitle Header
    elements.append(Paragraph(title, title_style))
    subtitle_text = f"Filter Scope: {filter_label} | Generated by SmartSched AI CSP Engine" if filter_label else "Institutional Weekly Academic Master Matrix | Generated by SmartSched AI CSP Engine"
    elements.append(Paragraph(subtitle_text, subtitle_style))
    elements.append(Spacer(1, 0.15 * inch))

    # Build 5-Day Weekly Matrix Table
    days = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday"]
    headers = ["Time Interval"] + days
    table_data = [[Paragraph(h, header_style) for h in headers]]

    card_code_style = ParagraphStyle(
        "CardCode",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=7.5,
        leading=9,
        textColor=colors.HexColor("#0f2d59"),
    )
    card_title_style = ParagraphStyle(
        "CardTitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=6.5,
        leading=8,
        textColor=colors.HexColor("#1e293b"),
    )
    card_sub_style = ParagraphStyle(
        "CardSub",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=6.0,
        leading=7.5,
        textColor=colors.HexColor("#475569"),
    )
    break_style = ParagraphStyle(
        "BreakText",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=7.5,
        leading=9,
        textColor=colors.HexColor("#92400e"),
        alignment=1,
    )

    if not schedule_records:
        empty_row = [Paragraph("09:00 - 10:00", cell_style)] + [Paragraph("No active timetable sessions found.", cell_style)] + [Paragraph("", cell_style) for _ in range(4)]
        table_data.append(empty_row)
    else:
        # Determine unique time intervals
        intervals_seen = set()
        intervals = []
        for r in schedule_records:
            st = r.get("start_time", "")
            et = r.get("end_time", "")
            if st and et:
                pair = (st, et)
                if pair not in intervals_seen:
                    intervals_seen.add(pair)
                    intervals.append(pair)
        intervals.sort(key=lambda x: x[0])

        for st, et in intervals:
            time_label = f"{st} - {et}"
            row = [Paragraph(f"<b>{time_label}</b>", cell_style)]

            for day in days:
                matching = [r for r in schedule_records if r.get("day") == day and r.get("start_time") == st]
                if not matching:
                    row.append(Paragraph("<font color='#cbd5e1'>Available</font>", cell_style))
                else:
                    cell_flowables = []
                    for m in matching:
                        code = m.get("course_code", "")
                        room = m.get("room_id", "")
                        ctitle = m.get("course_title", "")
                        faculty = m.get("faculty_name", m.get("faculty_id", ""))
                        cohort = m.get("group_name", m.get("group_id", ""))
                        is_lab = m.get("room_type") == "Laboratory" or "Lab" in ctitle or "Practical" in str(m.get("course_category", ""))

                        badge_color = "#047857" if is_lab else "#0284c7"
                        text = (
                            f"<b>{code}</b> [{room}]<br/>"
                            f"{ctitle[:32]}<br/>"
                            f"<i>{faculty}</i><br/>"
                            f"<font color='{badge_color}'>{cohort}</font>"
                        )
                        cell_flowables.append(Paragraph(text, card_title_style))
                    row.append(cell_flowables[0] if len(cell_flowables) == 1 else cell_flowables)
            table_data.append(row)

    col_widths = [1.1 * inch, 1.8 * inch, 1.8 * inch, 1.8 * inch, 1.8 * inch, 1.8 * inch]
    t = Table(table_data, colWidths=col_widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0D47A1")),
        ("ALIGN", (0, 0), (0, -1), "LEFT"),
        ("ALIGN", (1, 1), (-1, -1), "LEFT"),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CFD8DC")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.HexColor("#FFFFFF"), colors.HexColor("#F8FAFC")]),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
    ]))

    elements.append(t)
    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()
