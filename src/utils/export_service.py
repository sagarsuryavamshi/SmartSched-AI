"""Timetable Export Services for CSV and PDF.

Provides high-fidelity, institution-ready tabular CSV exports and
professional styled PDF documents for faculty, classrooms, and student cohorts.
"""

import io
from typing import Any, Dict, List, Optional
import pandas as pd

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter, landscape
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

from src.utils.logger import setup_logger

logger = setup_logger("smartsched.utils.export")


def export_timetable_to_csv(schedule_records: List[Dict[str, Any]]) -> str:
    """Converts timetable schedule records to a standardized CSV format."""
    if not schedule_records:
        return "Assignment ID,Course Code,Course Title,Day,Start Time,End Time,Classroom,Instructor,Cohort\n"

    rows = []
    for r in schedule_records:
        rows.append({
            "Assignment ID": r.get("assignment_id", ""),
            "Course Code": r.get("course_code", ""),
            "Course Title": r.get("course_title", ""),
            "Category": r.get("course_category", "Theory"),
            "Day": r.get("day", ""),
            "Start Time": r.get("start_time", ""),
            "End Time": r.get("end_time", ""),
            "Classroom": r.get("room_id", ""),
            "Room Type": r.get("room_type", ""),
            "Instructor": r.get("faculty_name", r.get("faculty_id", "")),
            "Cohort": r.get("group_name", r.get("group_id", "")),
        })

    df = pd.DataFrame(rows)
    day_order = {"Monday": 1, "Tuesday": 2, "Wednesday": 3, "Thursday": 4, "Friday": 5, "Saturday": 6}
    df["day_num"] = df["Day"].map(day_order)
    df.sort_values(by=["day_num", "Start Time", "Classroom"], inplace=True)
    df.drop(columns=["day_num"], inplace=True)

    return df.to_csv(index=False)


def export_timetable_to_pdf(
    schedule_records: List[Dict[str, Any]],
    title: str = "SmartSched AI University Timetable",
    filter_label: Optional[str] = None,
) -> bytes:
    """Generates an institutional landscape PDF document of the timetable."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=landscape(letter),
        rightMargin=0.5 * inch,
        leftMargin=0.5 * inch,
        topMargin=0.5 * inch,
        bottomMargin=0.5 * inch,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#0D47A1"),
        alignment=0,
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#546E7A"),
        alignment=0,
    )
    cell_style = ParagraphStyle(
        "TableCell",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8,
        leading=10,
        alignment=0,
    )
    header_style = ParagraphStyle(
        "TableHeader",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.white,
        alignment=0,
    )

    elements = []

    # Title & Subtitle Header
    elements.append(Paragraph(title, title_style))
    subtitle_text = f"Filter Scope: {filter_label} | Generated by SmartSched AI CSP Engine" if filter_label else "Institutional Master Schedule | Generated by SmartSched AI CSP Engine"
    elements.append(Paragraph(subtitle_text, subtitle_style))
    elements.append(Spacer(1, 0.2 * inch))

    # Table Header & Data Rows
    headers = ["Day", "Time Slot", "Course Code", "Course Title", "Room", "Room Type", "Instructor", "Student Cohort"]
    table_data = [[Paragraph(h, header_style) for h in headers]]

    if not schedule_records:
        empty_row = [Paragraph("No active timetable assignments found for this selection.", cell_style)] + [Paragraph("", cell_style) for _ in range(7)]
        table_data.append(empty_row)
    else:
        df = pd.DataFrame(schedule_records)
        day_order = {"Monday": 1, "Tuesday": 2, "Wednesday": 3, "Thursday": 4, "Friday": 5, "Saturday": 6}
        if "day" in df.columns:
            df["day_num"] = df["day"].map(day_order)
            df.sort_values(by=["day_num", "start_time", "room_id"], inplace=True)

        for _, r in df.iterrows():
            time_slot = f"{r.get('start_time', '')} - {r.get('end_time', '')}"
            row = [
                Paragraph(str(r.get("day", "")), cell_style),
                Paragraph(time_slot, cell_style),
                Paragraph(str(r.get("course_code", "")), cell_style),
                Paragraph(str(r.get("course_title", "")), cell_style),
                Paragraph(str(r.get("room_id", "")), cell_style),
                Paragraph(str(r.get("room_type", "")), cell_style),
                Paragraph(str(r.get("faculty_name", r.get("faculty_id", ""))), cell_style),
                Paragraph(str(r.get("group_name", r.get("group_id", ""))), cell_style),
            ]
            table_data.append(row)

    col_widths = [1.0 * inch, 1.2 * inch, 1.0 * inch, 2.2 * inch, 0.8 * inch, 1.0 * inch, 1.5 * inch, 1.3 * inch]
    t = Table(table_data, colWidths=col_widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0D47A1")),
        ("ALIGN", (0, 0), (-1, -1), "LEFT"),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CFD8DC")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.HexColor("#FFFFFF"), colors.HexColor("#F5F7FA")]),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))

    elements.append(t)
    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()
